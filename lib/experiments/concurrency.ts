/**
 * Runs `fn` over every item with at most `limit` in flight at once, preserving output order.
 * Section 19.3: "the runner needs parallel requests." A worker-pool shape rather than chunking,
 * so a slow item doesn't stall a whole batch waiting for the rest of its chunk.
 */
export async function mapWithConcurrency<T, R>(items: T[], limit: number, fn: (item: T, index: number) => Promise<R>): Promise<R[]> {
  const results: R[] = new Array(items.length);
  let nextIndex = 0;

  async function worker(): Promise<void> {
    while (true) {
      const i = nextIndex++;
      if (i >= items.length) return;
      results[i] = await fn(items[i]!, i);
    }
  }

  const workerCount = Math.max(1, Math.min(limit, items.length));
  await Promise.all(Array.from({ length: workerCount }, () => worker()));
  return results;
}
